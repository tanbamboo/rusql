export function renderBody(phase, issue) {
  const extraHuman =
    issue.extraLabels?.includes('needs-human') || phase.defaultExtraLabels?.includes('needs-human')
      ? '\n\n**Sequencing**: not `agent-ready`. Phase X / ADR-gated work stays `needs-human` until an ADR is accepted. Do not start while M114 file boundaries overlap.'
      : '\n\n**Sequencing**: not `agent-ready` until prior-phase dependencies are on `main` and file boundaries do not overlap in-flight M114. Default: leave unlabeled.';
  return `## Goal

${issue.goal}

## Category

Phase ${phase.letter} — ${phase.title} (${issue.id}). See ${ROADMAP}.

## Background

${issue.background}
${extraHuman}

## Acceptance Criteria

${issue.acceptance.map((a) => `- [ ] ${a}`).join('\n')}

## File Boundaries

Allowed:
${issue.allowed.map((a) => `- ${a}`).join('\n')}

Forbidden:
${issue.forbidden.map((a) => `- ${a}`).join('\n')}

## Negative Constraints

${issue.negatives.map((a) => `- ${a}`).join('\n')}

## Test plan

\`\`\`bash
${issue.tests}
\`\`\`
`;
}

export function bodyFileName(issue) {
  return `issue-${issue.id.toLowerCase()}-${issue.slug}.md`;
}

export function allIssues() {
  const out = [];
  for (const phase of PHASES) {
    for (const issue of phase.issues) {
      out.push({ phase, issue });
    }
  }
  return out;
}
